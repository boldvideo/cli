/**
 * Generate the single-page reference from the registered commands and editorial parts.
 * Re-run `bun run docs:reference` on every release, including after sibling command
 * branches merge. Only the current registry is rendered; no command list is pinned here.
 */
import { readFile, writeFile } from "node:fs/promises";
import { version } from "../package.json";
import { commands } from "../src/commands";
import { commandTreeToMarkdown } from "../src/docs-markdown";
import { commandTree, rootCommand } from "../src/help";

const docs = new URL("../docs/", import.meta.url);
const part = async (name: string) =>
	(await readFile(new URL(`reference-parts/${name}.md`, docs), "utf8")).trim();
const rendered = commandTreeToMarkdown(commandTree(rootCommand(commands)));
// The offline renderer owns command tables and exits. Replace its short intro
// with the fuller site sections, without maintaining a second command renderer.
const commandsStart = rendered.indexOf("\n## Commands\n");
const exitsStart = rendered.lastIndexOf("\n## Exit codes\n");
if (commandsStart < 0 || exitsStart <= commandsStart)
	throw new Error("The command renderer must include Commands and Exit codes.");

const sections = [
	"# boldvideo CLI reference",
	await part("install"),
	await part("auth"),
	await part("output"),
	rendered.slice(commandsStart, exitsStart).trim(),
	await part("recipes"),
	rendered.slice(exitsStart).trim(),
	await part("exit-codes"),
];
// Keep the generated/version comment in YAML: HTML comments are invalid MDX.
const frontmatter = `---\n# Generated by bun run docs:reference from boldvideo ${version}. Do not edit this file directly.\ntitle: "CLI Reference"\ndescription: "Install, authenticate and use every boldvideo CLI command, with flags, examples, recipes and exit codes."\n---`;
// Spec prose can contain braces or angle brackets. Escape them outside code so
// the same Markdown is literal text in MDX, not a JSX tag or JS expression.
const body = sections
	.join("\n\n")
	.replace(
		/```[\s\S]*?```|`[^`\n]*`|[<>{}]/g,
		(token) =>
			({ "<": "&lt;", ">": "&gt;", "{": "&#123;", "}": "&#125;" })[token] ??
			token,
	);
await writeFile(
	new URL("cli-reference.md", docs),
	`${frontmatter}\n\n${body}\n`,
);
