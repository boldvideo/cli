import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const tree = JSON.parse(
	execFileSync("node", ["dist/boldvideo.js", "help", "--json"], {
		encoding: "utf8",
	}),
);
const rows = [];
function walk(command, parent = []) {
	const path = [...parent, command.name];
	rows.push(
		`| \`${path.join(" ")}\` | ${command.flags.map((flag) => `\`--${flag.name}\``).join(", ")} |`,
	);
	for (const child of command.subcommands ?? []) walk(child, path);
}
walk(tree);
writeFileSync(
	"docs/baseline-0.1.0.md",
	[
		"# boldvideo 0.1.0 stability baseline",
		"",
		"Generated by `bun run baseline:generate` from the built `boldvideo help --json`.",
		"After release, existing commands and flags are permanent; additions only.",
		"",
		"| Command | Flags |",
		"| --- | --- |",
		...rows,
		"",
	].join("\n"),
);
