import { expect, test } from "bun:test";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { version } from "../package.json";
import { parse } from "../src/cli";
import { commands } from "../src/commands";
import { commandTree, rootCommand } from "../src/help";
import type { Command } from "../src/spec";
import { run } from "./run";
import { words } from "./words";

test("reference generation is deterministic and covers every registered command and flag", async () => {
	const path = resolve("docs/cli-reference.md");
	const committed = await readFile(path, "utf8");
	const result = await run(["bun", "run", "docs:reference"]);
	expect(result.status).toBe(0);
	const markdown = await readFile(path, "utf8");
	expect(markdown).toBe(committed);
	expect(markdown).toStartWith(
		`---\n# Generated by bun run docs:reference from boldvideo ${version}.`,
	);
	expect(markdown).toContain('\ntitle: "CLI Reference"\n');
	expect(markdown).toContain(
		"--json returns &#123;url, title, markdown&#125;.",
	);
	expect(markdown).not.toContain("<!--");
	function check(command: Command, parents: string[]) {
		const invocation = [...parents, command.name];
		const start = markdown.indexOf(`### ${invocation.join(" ")}\n`);
		expect(start).toBeGreaterThanOrEqual(0);
		const end = markdown.indexOf("\n### ", start + 1);
		const section = markdown.slice(start, end < 0 ? undefined : end);
		for (const flag of command.flags ?? [])
			expect(section).toContain(`| --${flag.name} | ${flag.type} |`);
		for (const example of command.examples)
			expect(section).toContain(`\n${example.cmd}\n`);
		for (const child of command.subcommands ?? []) check(child, invocation);
	}
	check(commandTree(rootCommand(commands)), []);
});

test("documented shell invocations parse without executing handlers", async () => {
	const markdown = await readFile(resolve("docs/cli-reference.md"), "utf8");
	let checked = 0;
	// Like the contract examples: tokenize shell words, then call the real parser.
	// No shell execution, credentials, network calls or write handlers are needed.
	for (const block of markdown.matchAll(/```sh\n([\s\S]*?)\n```/g)) {
		for (const line of block[1]?.split("\n") ?? []) {
			if (!line.startsWith("boldvideo ") || line.endsWith("[flags]")) continue;
			expect(() => parse(words(line)), line).not.toThrow();
			checked++;
		}
	}
	expect(checked).toBeGreaterThan(0);
});
