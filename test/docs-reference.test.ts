test("reference generation is deterministic and covers every registered command and flag", async () => {
	const path = resolve("docs/cli-reference.md");
	const committed = await readFile(path, "utf8");
	const result = await run(["bun", "run", "docs:reference"]);
	expect(result.status).toBe(0);
	const markdown = await readFile(path, "utf8");
	expect(markdown).toBe(committed);
	expect(markdown).toStartWith(
		`---\n# Generated by bun run docs:reference from boldvideo ${version}.`,
	);
	expect(markdown).toContain('\ntitle: "Bold Video CLI (boldvideo)"\n');
	expect(markdown).toContain(
		"--json returns &#123;url, title, markdown&#125;.",
	);
	expect(markdown).not.toContain("<!--");
	function check(command: Command, parents: string[]) {
		const invocation = [...parents, command.name];
		const start = markdown.indexOf(`## ${invocation.join(" ")}\n`);
		expect(start).toBeGreaterThanOrEqual(0);
		const end = markdown.indexOf("\n## ", start + 1);
		const section = markdown.slice(start, end < 0 ? undefined : end);
		expect(section).toContain(" [flags]\n```");
		expect(section).toContain("\n### Flags\n");
		expect(section).toContain("\n### Examples\n");
		for (const flag of command.flags ?? [])
			expect(section).toContain(`| --${flag.name} | ${flag.type} |`);
		for (const example of command.examples)
			expect(section).toContain(`\n${example.cmd}\n`);
		for (const child of command.subcommands ?? []) check(child, invocation);
	}
	check(commandTree(rootCommand(commands)), []);
});

test("reference follows the single-page layout with visible version and five recipes", async () => {
	const markdown = await readFile(resolve("docs/cli-reference.md"), "utf8");
	const body = markdown.replace(/^---\n[\s\S]*?\n---\n/, "").trim();
	expect(body.split("\n\n")[0]).toBe("# Bold Video CLI (boldvideo)");
	expect(body.split("\n\n")[1]).toContain("Bold Video CLI");
	expect(body.split("\n\n")[1]).toContain("`boldvideo`");
	expect(body).toContain(`Generated from CLI version **${version}**.`);
	expect(body).not.toContain("\t");
	const headings = [...body.matchAll(/^## .+$/gm)].map(([heading]) => heading);
	expect(new Set(headings).size).toBe(headings.length);
	expect(headings.slice(0, 3)).toEqual([
		"## Install",
		"## Authenticate",
		"## Quick start",
	]);
	expect(
		headings
			.slice(3, -3)
			.every((heading) => heading.startsWith("## boldvideo")),
	).toBe(true);
	expect(headings.slice(-3)).toEqual([
		"## Recipes",
		"## Exit codes",
		"## Error shape",
	]);
	const install = body.split("## Install\n\n")[1]?.split("\n\n## ")[0];
	expect(install?.split("\n")).toHaveLength(1);
	const authenticate =
		body.split("## Authenticate\n")[1]?.split("\n## ")[0] ?? "";
	expect(authenticate).toContain("boldvideo login");
	expect(authenticate).toContain("| Admin key (`bold_admin_…`) |");
	expect(authenticate).toContain("| API key (`bold_live_…`) |");
	const quickStart = body.split("## Quick start\n")[1]?.split("\n## ")[0] ?? "";
	const demo = quickStart.match(/```sh\n([\s\S]*?)\n```/)?.[1]?.split("\n");
	expect(demo).toHaveLength(4);
	expect(demo?.[0]).toBe("boldvideo login");
	expect(demo?.[1]).toStartWith("boldvideo import ");
	expect(demo?.[1]).toEndWith(" --wait");
	expect(demo?.[2]).toStartWith("boldvideo ask ");
	expect(demo?.[3]).toStartWith("boldvideo search ");
	expect(quickStart).not.toContain("not registered");
	const recipes = body.split("## Recipes\n")[1]?.split("\n## ")[0] ?? "";
	expect(
		[...recipes.matchAll(/^### .+$/gm)].map(([heading]) => heading),
	).toEqual([
		"### Bulk-edit from a list pipeline",
		"### Weekly questions digest",
		"### Import a channel and ask",
		"### Kajabi migration from a folder of URLs",
		"### Customer onboarding: create collections, import, sync viewers",
	]);
	const sample = body.match(/```json\n([\s\S]*?)\n```/)?.[1] ?? "";
	const result = await run(["node", resolve("dist/boldvideo.js"), "hlep"]);
	expect(result.status).toBe(2);
	expect(JSON.parse(sample)).toEqual(JSON.parse(result.stderr));
});

test("documented shell invocations parse without executing handlers", async () => {
	const markdown = await readFile(resolve("docs/cli-reference.md"), "utf8");
	let checked = 0;
	// Like the contract examples: tokenize shell words, then call the real parser.
	// No shell execution, credentials, network calls or write handlers are needed.
	for (const block of markdown.matchAll(/```sh\n([\s\S]*?)\n```/g)) {
		for (const line of block[1]?.split("\n") ?? []) {
			if (!line.startsWith("boldvideo ") || line.endsWith("[flags]")) continue;
			expect(() => parse(words(line)), line).not.toThrow();
			checked++;
		}
	}
	expect(checked).toBeGreaterThan(0);
});
